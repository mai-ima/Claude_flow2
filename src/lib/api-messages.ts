/**
 * API ルートが返す文言。
 *
 * Server Action 側は safe-action.ts の ERROR_MESSAGES に集めてあるが、
 * ルート（ファイル送信・CSV・決済）はそれぞれの中で文字列を書いていた。
 * 同じ意味なのに「操作が集中しています」「続けて送りすぎです」
 * 「書き出しの回数が多すぎます」と3通りに割れており、利用者からは
 * 別の出来事に見える。同じ状況には同じ言い方をする。
 *
 * ここに無い文言は、その画面にしか無い事情を伝えるもの（ファイルの種類、
 * 大きさの上限など）。無理に共通化すると、かえって何が悪いのか
 * 分からなくなるので、そちらは各ルートに残す。
 */
export const API_MESSAGE = {
  /** 未ログイン。401 と一緒に返す。 */
  UNAUTHORIZED: "ログインが必要です。",
  /** 権限不足。403。 */
  FORBIDDEN: "この操作を行う権限がありません。",
  /** 対象が無い。404。 */
  NOT_FOUND: "対象が見つかりません。",
  /** 呼び出しが多すぎる。429。 */
  RATE_LIMITED: "続けて操作されています。少し時間をおいてからお試しください。",
  /** 成りすまし中の書き込み。403。 */
  IMPERSONATION_READONLY: "他のユーザーとして閲覧中は、変更操作を行えません。",
  /** 予期しない失敗。500。内部の事情は出さない。 */
  FAILED: "処理に失敗しました。時間をおいて再度お試しください。",
  /** 機能そのものが未設定。503。 */
  UNAVAILABLE: "ただいまご利用いただけません。",
} as const;
